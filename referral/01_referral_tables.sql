-- 10. Recent refusals per hospital (shared across coordinators: counts and reasons only, no patient data).
CREATE OR REPLACE VIEW workspace.datathon.hospital_refusals_30d
COMMENT 'Refusals in the last 30 days per hospital. Used for the search warning and rank penalty.' AS
SELECT hospital_id,
       max(hospital_name)        AS hospital_name,
       count(*)                  AS n_refusals,
       mode(reason)              AS top_reason,
       max(refused_at)           AS last_refused_at
FROM workspace.datathon.refusals
WHERE refused_at >= current_timestamp() - INTERVAL 30 DAYS AND hospital_id IS NOT NULL
GROUP BY hospital_id
