-- 2. Patients, kept separate from referrals.
CREATE TABLE IF NOT EXISTS workspace.datathon.patients (
  patient_id           STRING NOT NULL COMMENT 'UUID generated by the app',
  coordinator_email    STRING NOT NULL COMMENT 'Coordinator who owns this record; every query filters on it',
  name_or_code         STRING  COMMENT 'Patient name or a case code (demo data only)',
  age_years            INT,
  date_of_birth        DATE    COMMENT 'Optional',
  phone                STRING,
  address              STRING,
  condition            STRING  COMMENT 'What the patient needs, in plain words',
  consent_to_reminders BOOLEAN COMMENT 'Patient agreed to reminder calls/SMS; SMS is only (mock) sent when true',
  care_program         STRING,
  medical_history      STRING  COMMENT 'DEMO DATA ONLY - do not enter real patient data.',
  secondary_contacts   STRING,
  is_demo              BOOLEAN COMMENT 'Always true: this app holds demo data only',
  created_at           TIMESTAMP,
  updated_at           TIMESTAMP
) COMMENT 'DEMO DATA ONLY. Patients referred by coordinators. Do not enter real patient data.'
-- @@
-- 3. Call results: append-only events.
CREATE TABLE IF NOT EXISTS workspace.datathon.call_attempts (
  attempt_id        STRING NOT NULL,
  case_id           STRING NOT NULL,
  coordinator_email STRING NOT NULL,
  hospital_id       STRING,
  hospital_name     STRING,
  attempted_at      TIMESTAMP,
  channel           STRING COMMENT 'phone | whatsapp | in_person',
  result            STRING COMMENT 'accepted_slot | accepted_needs_prep | turned_away | no_answer',
  refusal_reason    STRING COMMENT 'no_machine | no_doctor | no_bed | too_expensive | other',
  note              STRING,
  callback_at       TIMESTAMP COMMENT 'Try-again reminder for no_answer',
  appointment_at    TIMESTAMP COMMENT 'What the hospital said: date/time (required when accepted)',
  what_to_bring     STRING    COMMENT 'What the hospital said (required when accepted)',
  spoke_to          STRING,
  prep_steps        STRING,
  cost_or_scheme    STRING
) COMMENT 'Append-only event log of calls to hospitals.'
TBLPROPERTIES ('delta.appendOnly' = 'true')
-- @@
-- 4. Refusals: append-only, one row each time a hospital turns a patient away (call or at the visit).
CREATE TABLE IF NOT EXISTS workspace.datathon.refusals (
  refusal_id        STRING NOT NULL,
  hospital_id       STRING,
  hospital_name     STRING,
  reason            STRING COMMENT 'no_machine | no_doctor | no_bed | too_expensive | other',
  note              STRING,
  refused_at        TIMESTAMP,
  refusal_date      DATE,
  source            STRING COMMENT 'call | visit',
  case_id           STRING,
  coordinator_email STRING
) COMMENT 'Append-only. Feeds the recent-refusals warning and rank penalty in search.'
TBLPROPERTIES ('delta.appendOnly' = 'true')
-- @@
